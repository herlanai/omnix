// One-shot T01 test skeleton generator. Reads TC-<task ID>-<number> table rows from
// docs/TEST_CASES.md and generates compilable, skipped placeholders in tests/tc_skeletons_test.go
// for cases marked as pending. Case IDs remain one-to-one; business logic is not generated. Run:
// go run ./cmd/gen_tc_skeletons.
package main

import (
	"bufio"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// tcRow represents a test case parsed from the table.
type tcRow struct {
	ID     string
	Kind   string
	Name   string
	Status string
	File   string
}

// tcID validates identifiers such as TC-M01-01: an alphanumeric task ID followed by a case number.
var tcID = regexp.MustCompile(`^TC-[A-Z]\d+-\d+$`)

func main() {
	root, _ := os.Getwd()
	docPath := filepath.Join(root, "docs", "TEST_CASES.md")
	outPath := filepath.Join(root, "tests", "tc_skeletons_test.go")

	f, err := os.Open(docPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "打开文档失败: %v\n", err)
		os.Exit(1)
	}
	defer f.Close()

	var rows []tcRow
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1024*1024), 1024*1024)
	for sc.Scan() {
		line := sc.Text()
		if !strings.HasPrefix(strings.TrimSpace(line), "|") {
			continue
		}
		// Split the table columns: ID, category, name, prerequisites, steps, expected result, status, and
		// related file.
		parts := strings.Split(line, "|")
		if len(parts) < 4 {
			continue
		}
		trim := func(s string) string { return strings.TrimSpace(s) }
		id := trim(parts[1])
		if !tcID.MatchString(id) {
			continue
		}
		var r tcRow
		r.ID = id
		if len(parts) >= 3 {
			r.Kind = trim(parts[2])
		}
		if len(parts) >= 4 {
			r.Name = trim(parts[3])
		}
		if len(parts) >= 8 {
			r.Status = trim(parts[7])
		}
		if len(parts) >= 9 {
			r.File = trim(parts[8])
		}
		rows = append(rows, r)
	}
	if err := sc.Err(); err != nil {
		fmt.Fprintf(os.Stderr, "读取文档失败: %v\n", err)
		os.Exit(1)
	}

	// Generate skeletons only for pending, uncovered cases.
	var pending []tcRow
	for _, r := range rows {
		if strings.Contains(r.Status, "待实现") {
			pending = append(pending, r)
		}
	}

	generated, err := generateSkeletons(pending)
	if err != nil {
		fmt.Fprintf(os.Stderr, "format generated tests: %v\n", err)
		os.Exit(1)
	}

	if err := os.WriteFile(outPath, generated, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "写文件失败: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("生成完成: %s（共 %d 条待实现骨架, 来源 %d 条 TC）\n", outPath, len(pending), len(rows))
}

// generateSkeletons renders skipped tests with English comments. Source metadata
// remains in quoted skip messages so Unicode, quotes, and newlines stay intact.
func generateSkeletons(rows []tcRow) ([]byte, error) {
	var sb strings.Builder
	sb.WriteString("// T01 test skeletons generated by go run ./cmd/gen_tc_skeletons.\n")
	sb.WriteString("// Source: pending cases in docs/TEST_CASES.md.\n")
	sb.WriteString("// Implement the documented assertions before removing each skip.\n")
	sb.WriteString("package tests\n\n")
	if len(rows) > 0 {
		sb.WriteString("import \"testing\"\n\n")
	}
	for _, r := range rows {
		fn := "TestTC" + strings.ReplaceAll(r.ID[3:], "-", "_")
		fmt.Fprintf(&sb, "// %s covers pending case %s from docs/TEST_CASES.md.\n", fn, r.ID)
		fmt.Fprintf(&sb, "func %s(t *testing.T) {\n", fn)
		message := fmt.Sprintf("T01 skeleton: %s; category: %s; name: %s", r.ID, orDash(r.Kind), orDash(r.Name))
		if r.File != "" && r.File != "—" && r.File != "-" {
			message += "; related file: " + r.File
		}
		fmt.Fprintf(&sb, "\tt.Skip(%q)\n}\n\n", message)
	}
	return format.Source([]byte(sb.String()))
}

func orDash(s string) string {
	if s == "" || s == "—" || s == "-" {
		return "-"
	}
	return s
}
