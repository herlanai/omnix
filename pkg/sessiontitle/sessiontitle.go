// Package sessiontitle generates session titles (S08), matching storage/session-title.
// Session events and FoldSessionTitle already provide latest-wins title projection.
// This package generates titles from the first user message: Fallback takes a
// 30-rune prefix by default, while an optional LLMAdapter generates a concise title.
// Missing or failed LLM generation falls back to the prefix. Rune-based truncation
// preserves UTF-8 characters. Generate returns both Title and Source (llm/fallback).
package sessiontitle

import (
	"context"
	"strings"

	"github.com/herlanai/omnix/pkg/llm"
)

// Constants and defaults.

// defaultMaxRunes limits fallback titles to the upstream default of 30 runes.
const defaultMaxRunes = 30

// Source identifies how a title was generated.
type Source string

// Title sources.
const (
	SourceLLM      Source = "llm"      // Generated by the LLM helper.
	SourceFallback Source = "fallback" // Generated by truncating a prefix.
)

// Truncation helpers.

// truncateRunes truncates at Unicode code-point boundaries and appends an
// ellipsis when needed, preserving multibyte UTF-8 characters.
func truncateRunes(s string, max int) string {
	if max <= 0 {
		return ""
	}
	runes := []rune(strings.TrimSpace(s))
	if len(runes) <= max {
		return string(runes)
	}
	return string(runes[:max]) + "…"
}

// Fallback uses the first user-message prefix, up to 30 runes by default.
// Empty input returns empty; callers decide whether to emit session/title.
func Fallback(firstUserMessage string) string {
	return FallbackMax(firstUserMessage, defaultMaxRunes)
}

// FallbackMax generates a prefix title with the supplied rune limit.
func FallbackMax(firstUserMessage string, maxRunes int) string {
	return truncateRunes(firstUserMessage, maxRunes)
}

// Title generation with an optional LLM and fallback.

// Generator creates session titles using an optional LLM helper.
type Generator struct {
	// LLM optionally summarizes the first user message; nil always uses fallback.
	LLM llm.LLMAdapter
	// Model selects the title model; empty uses the adapter default.
	Model string
	// MaxRunes limits fallback titles; nonpositive values use 30.
	MaxRunes int
	// System optionally overrides the built-in title-generation prompt.
	System string
	// MaxTokens limits tokens for one LLM title request.
	MaxTokens int
}

// Result contains a generated title and its source.
type Result struct {
	Title  string `json:"title"`
	Source Source `json:"source"`
}

// FallbackSystemPrompt asks the model for a concise single-sentence title.
var FallbackSystemPrompt = "你是一名标题提炼助手。根据用户的输入，用一句不超过 15 个字的中文概括其意图，只输出标题本身，不要引号、不要解释。"

// maxRunes returns the effective fallback rune limit.
func (g *Generator) maxRunes() int {
	if g == nil || g.MaxRunes <= 0 {
		return defaultMaxRunes
	}
	return g.MaxRunes
}

// fallbackSystem returns the effective LLM system prompt.
func (g *Generator) fallbackSystem() string {
	if g == nil || g.System == "" {
		return FallbackSystemPrompt
	}
	return g.System
}

// Generate prefers the LLM helper, falling back to a prefix when unavailable or failed.
func (g *Generator) Generate(ctx context.Context, firstUserMessage string) Result {
	// Compute a fallback regardless of whether the LLM is enabled.
	fallback := FallbackMax(firstUserMessage, g.maxRunes())

	if g == nil || g.LLM == nil || strings.TrimSpace(firstUserMessage) == "" {
		return Result{Title: fallback, Source: SourceFallback}
	}

	title, err := g.generateFromLLM(ctx, firstUserMessage)
	if err != nil || strings.TrimSpace(title) == "" {
		// Failed or empty LLM output uses the prefix title.
		return Result{Title: fallback, Source: SourceFallback}
	}
	return Result{Title: truncateRunes(title, g.maxRunes()), Source: SourceLLM}
}

// generateFromLLM aggregates only text chunks and performs basic cleanup.
func (g *Generator) generateFromLLM(ctx context.Context, firstUserMessage string) (string, error) {
	req := llm.ChatRequest{
		Model:       g.Model,
		System:      g.fallbackSystem(),
		Messages:    []llm.Message{llm.NewUserMessage(firstUserMessage)},
		MaxTokens:   g.MaxTokens,
		Temperature: 0.2, // Use low-temperature sampling for stable titles.
	}
	var sb strings.Builder
	_, err := g.LLM.Chat(ctx, req, func(c llm.StreamChunk) {
		if c.Kind == llm.ChunkText {
			sb.WriteString(c.Text)
		}
	})
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(TrimTitle(sb.String())), nil
}

// TrimTitle removes surrounding quotes, periods, and similar LLM output decoration.
func TrimTitle(s string) string {
	s = strings.TrimSpace(s)
	s = strings.Trim(s, "\"'「」『』《》【】。，、；：！？. ")
	return s
}
